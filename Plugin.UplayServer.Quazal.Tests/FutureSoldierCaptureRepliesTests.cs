        byte[] results = FutureSoldierServices.Sessions.BuildSearchSessionsResult(Request(42, 7, SearchSessionsRequest), Searcher, Title);
        Assert.Equal(1u, ResultCount(results));

        // Same record layout as the working server's one result: key, host,
        // URLs, then the host's attributes plus 5, 6, 50 and 51.
        static (uint Session, uint Host, List<string> Urls, Dictionary<uint, int> Attributes) Record(byte[] bytes)
        {
            int o = 4;
            Assert.Equal(1u, BinaryPrimitives.ReadUInt32LittleEndian(bytes.AsSpan(o))); o += 4;
            uint session = BinaryPrimitives.ReadUInt32LittleEndian(bytes.AsSpan(o)); o += 4;
            uint host = BinaryPrimitives.ReadUInt32LittleEndian(bytes.AsSpan(o)); o += 4;
            uint urlCount = BinaryPrimitives.ReadUInt32LittleEndian(bytes.AsSpan(o)); o += 4;
            var urls = new List<string>();
            for (uint u = 0; u < urlCount; u++)
            {
                int len = BinaryPrimitives.ReadUInt16LittleEndian(bytes.AsSpan(o));
                urls.Add(Encoding.UTF8.GetString(bytes, o + 2, len - 1)); o += 2 + len;
            }
            uint count = BinaryPrimitives.ReadUInt32LittleEndian(bytes.AsSpan(o)); o += 4;
            var attributes = new Dictionary<uint, int>();
            for (uint a = 0; a < count; a++) { attributes[BinaryPrimitives.ReadUInt32LittleEndian(bytes.AsSpan(o))] = BinaryPrimitives.ReadInt32LittleEndian(bytes.AsSpan(o + 4)); o += 8; }
            Assert.Equal(bytes.Length, o);
            return (session, host, urls, attributes);
        }
        var ours = Record(results);
        var working = Record(Convert.FromHexString(SearchSessionsReply));
        Assert.Equal(theirs, ours.Session);
        Assert.Equal(Host, ours.Host);
        Assert.Equal(working.Urls, ours.Urls);
        // The host's own fourteen creation attributes, as it sent them.
        foreach (uint id in new uint[] { 7, 3, 4, 100, 101, 116, 105, 115, 103, 113, 114, 112, 117, 102 })
            Assert.True(ours.Attributes.ContainsKey(id), $"attribute {id} missing");
        Assert.Equal(1, ours.Attributes[5]);
        Assert.Equal(0, ours.Attributes[6]);
        Assert.Equal(working.Attributes[50], ours.Attributes[50]);
        Assert.Equal(working.Attributes[51], ours.Attributes[51]);
        Assert.Equal(working.Attributes.Keys.Order(), ours.Attributes.Keys.Order());

        // The searcher's own session is not offered to them.
        Assert.Equal(1u, ResultCount(FutureSoldierServices.Sessions.BuildSearchSessionsResult(Request(42, 7, SearchSessionsRequest), Searcher, Title)));
        Assert.Equal(1u, ResultCount(FutureSoldierServices.Sessions.BuildSearchSessionsResult(Request(42, 7, SearchSessionsRequest), Host, Title)));
        Assert.NotEqual(theirs, Record(FutureSoldierServices.Sessions.BuildSearchSessionsResult(Request(42, 7, SearchSessionsRequest), Host, Title)).Session);

        // Abandoning tears the searcher's session down; leaving one they were never in changes nothing.
        Assert.Empty(FutureSoldierServices.Sessions.BuildLeaveResult(Request(42, 5, Key(theirs)), Searcher, "LeaveSession", Title));
        Assert.Empty(FutureSoldierServices.Sessions.BuildLeaveResult(Request(42, 23, Key(own)), Searcher, "AbandonSession", Title));
        Assert.Equal(0u, ResultCount(FutureSoldierServices.Sessions.BuildSearchSessionsResult(Request(42, 7, SearchSessionsRequest), Host, Title)));
        Assert.Equal([Host], GameSessionStore.GetParticipants(Title, 1, theirs));

        // SearchSessionsWithParticipants: nothing for nobody, the roster for a member.
        Assert.Equal("00000000", Hex(FutureSoldierServices.Sessions.BuildSearchSessionsWithParticipantsResult(Request(42, 24, "0100000000000000"), Title)!));
        Assert.Equal("01000000" + "01000000" + "1b190000", Hex(FutureSoldierServices.Sessions.BuildSearchSessionsWithParticipantsResult(
            Request(42, 24, "01000000" + "01000000" + Convert.ToHexString(BitConverter.GetBytes(Host))), Title)!));
        GameSessionStore.DeleteSession(Title, 1, theirs);
    }

