    [Fact]
    public void WrittenStatisticsComeBackAsTheWorkingServerReturnedThem()
    {
        Assert.Empty(FutureSoldierServices.PlayerStatistics.BuildWriteResult(Request(108, 1, Write32Request), Pid, Title, 4)!);
        Assert.Empty(FutureSoldierServices.PlayerStatistics.BuildWriteResult(Request(108, 2, Write64Request), Pid, Title, 8)!);

        // The captured reads list more rows than these two writes put there
        // (the account's first, 10 KB upload was not reassembled); what the
        // writes did put there must come back exactly as the working server
        // listed it, and nothing else may.
        foreach ((string request, string reply, int width) in new[] { (Read32Request, Read32Reply, 4), (Read64Request, Read64Reply, 8) })
        {
            var expected = Rows(Convert.FromHexString(reply), width, out uint pid);
            Assert.Equal(Pid, pid);
            var actual = Rows(FutureSoldierServices.PlayerStatistics.BuildReadResult(Request(108, (uint)(width == 4 ? 6 : 7), request), Title, width)!, width, out pid);
            Assert.Equal(Pid, pid);
            Assert.NotEmpty(actual);
            foreach ((string address, Dictionary<byte, string> row) in actual)
            {
                Assert.True(expected.TryGetValue(address, out var theirs), $"row {address} was not in the working server's reply");
                Assert.Equal(theirs.OrderBy(c => c.Key), row.OrderBy(c => c.Key));
            }
        }

        // A query naming columns a board's rows do not hold lists nothing --
        // boards 10 and 13 came back empty on the working server too.
