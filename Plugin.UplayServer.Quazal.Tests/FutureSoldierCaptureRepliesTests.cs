    [Fact]
    public void TheNewsItemHasTheWorkingServersShape()
    {
        Assert.Equal(0x1F78D4C621UL, FutureSoldierServices.QuazalDateTime(new DateTimeOffset(2014, 3, 10, 12, 24, 33, TimeSpan.Zero)));

        var at = new DateTimeOffset(2014, 3, 10, 12, 24, 33, TimeSpan.Zero);
        byte[] ours = FutureSoldierServices.OverlordNews.BuildGetNewsResult(at);
        byte[] theirs = Convert.FromHexString(NewsReply);
        static List<object> Walk(byte[] bytes)
        {
            var fields = new List<object>();
            int o = 0;
            uint count = BinaryPrimitives.ReadUInt32LittleEndian(bytes.AsSpan(o)); o += 4;
            fields.Add(count);
            for (int n = 0; n < 4; n++) { fields.Add(BinaryPrimitives.ReadUInt32LittleEndian(bytes.AsSpan(o))); o += 4; }
            string Str() { int len = BinaryPrimitives.ReadUInt16LittleEndian(bytes.AsSpan(o)); string s = Encoding.UTF8.GetString(bytes, o + 2, len - 1); o += 2 + len; return s; }
            fields.Add(Str());
            for (int n = 0; n < 3; n++) { fields.Add(BinaryPrimitives.ReadUInt64LittleEndian(bytes.AsSpan(o))); o += 8; }
            fields.Add(Str()); fields.Add(Str()); fields.Add(Str());
            Assert.Equal(bytes.Length, o);
            return fields;
        }
        List<object> a = Walk(ours), b = Walk(theirs);
        Assert.Equal(b.Take(5), a.Take(5));                      // count, id, the three unknowns
        Assert.Equal(b.Skip(6).Take(3), a.Skip(6).Take(3));      // the stamps, at the captured time
        Assert.Equal(FutureSoldierServices.OverlordNews.Title, a[9]);
    }

    /// <summary>Rows as (board, keys) -> column -> value, so order does not matter.</summary>
    private static Dictionary<string, Dictionary<byte, string>> Rows(byte[] reply, int width, out uint pid)
    {
        var rows = new Dictionary<string, Dictionary<byte, string>>();
        int o = 0;
        Assert.Equal(1u, BinaryPrimitives.ReadUInt32LittleEndian(reply.AsSpan(o))); o += 4;
        pid = BinaryPrimitives.ReadUInt32LittleEndian(reply.AsSpan(o)); o += 4;
        uint count = BinaryPrimitives.ReadUInt32LittleEndian(reply.AsSpan(o)); o += 4;
        for (uint r = 0; r < count; r++)
        {
            byte board = reply[o]; byte keyCount = reply[o + 1];
            Assert.Equal(0, reply[o + 2] | reply[o + 3] | reply[o + 4]);
            o += 5;
            var keys = new List<uint>();
            for (int k = 0; k < keyCount; k++) { keys.Add(BinaryPrimitives.ReadUInt32LittleEndian(reply.AsSpan(o))); o += 4; }
            uint values = BinaryPrimitives.ReadUInt32LittleEndian(reply.AsSpan(o)); o += 4;
            var row = new Dictionary<byte, string>();
            for (uint v = 0; v < values; v++) { row[reply[o]] = Convert.ToHexString(reply, o + 1, width); o += 1 + width; }
            rows[$"{board}:{string.Join(',', keys)}"] = row;
        }
        Assert.Equal(reply.Length, o);
        return rows;
    }

